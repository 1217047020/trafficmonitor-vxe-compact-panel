// Build-time only: SVG -> embedded alpha masks. Production needs no image files.
const fs = require('fs');
const path = require('path');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');
const sizes = [14, 18, 21, 28, 35, 42, 56, 84];
const names = ['mouse', 'controller', 'earcase'];
(async () => {
  const blocks = ['// Generated by tools/generate_device_icons.cjs; do not edit.\n' +
    '// M3: Phosphor Icons / MIT. G5, E3: Solar / 480 Design / CC BY 4.0.\n' +
    '// Source SVGs and attribution: assets/device-icons/, THIRD_PARTY_NOTICES.md.\n' +
    '#pragma once\n#include <cstdint>\nnamespace compact { namespace device_art {\n' +
    'struct Mask { int size; const std::uint8_t* alpha; };\n'];
  for (const name of names) {
    const svg = fs.readFileSync(path.join(root, 'traffic-plugin/assets/device-icons', name + '.svg'), 'utf8')
      .replaceAll('currentColor', '#ffffff').replace(/width="24" height="24"/, 'width="336" height="336"');
    const master = await sharp(Buffer.from(svg)).png().toBuffer();
    for (const size of sizes) {
      const {data, info} = await sharp(master).resize(size, size).ensureAlpha().raw().toBuffer({resolveWithObject: true});
      const alpha = Array.from({length: size * size}, (_, i) => data[i * info.channels + info.channels - 1]);
      const rows = [];
      for (let i = 0; i < alpha.length; i += 32) rows.push('  ' + alpha.slice(i, i + 32).join(','));
      blocks.push(`inline constexpr std::uint8_t ${name}_${size}[] = {\n${rows.join(',\n')}\n};\n`);
    }
  }
  blocks.push('inline constexpr Mask masks[3][8] = {\n' + names.map(n =>
    '  {' + sizes.map(s => `{${s},${n}_${s}}`).join(',') + '}').join(',\n') + '\n};\n} }\n');
  fs.writeFileSync(path.join(root, 'traffic-plugin/device_icon_masks.h'), blocks.join(''));
  console.log('Generated 3 embedded icon families at 8 raster sizes; no runtime file dependency.');
})().catch(e => { console.error(e); process.exitCode = 1; });
